"""
Voice Contract and Audio Artifacts generated by the Voice Director Agent.
"""
from typing import List, Optional
from pydantic import BaseModel, Field


class SceneAudioArtifact(BaseModel):
    """
    Per-scene synthesized audio artifact with exact measured duration.
    """
    scene_id: int
    audio_path: str
    measured_duration_sec: float = Field(..., description="Exact duration in seconds probed via ffprobe")
    sample_rate_hz: int = 44100
    format: str = "mp3"


class VoiceContract(BaseModel):
    """
    Complete audio production package verified for downstream AV synchronization.
    """
    voice_profile_used: str
    engine: str  # 'edge_tts', 'elevenlabs', or 'kokoro_local'
    pitch: str = "+0Hz"
    speech_rate: float = 1.0
    master_audio_path: str
    subtitles_srt_path: Optional[str] = None
    total_audio_duration_sec: float
    scene_audios: List[SceneAudioArtifact]
    normalized_lufs: Optional[float] = None
    bg_music_applied: bool = False
