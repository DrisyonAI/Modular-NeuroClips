"""
Visual Contract and Image/Avatar Artifacts generated by the Image Generator Agent.
"""
from typing import List, Optional
from pydantic import BaseModel, Field


class SceneVisualArtifact(BaseModel):
    """
    Per-scene visual asset generated or selected.
    """
    scene_id: int
    visual_type: str = Field(default="ai_image", description="'ai_image', 'ai_video', or 'uploaded_video'")
    media_path: str
    aspect_ratio: str = "16:9"
    avatar_overlay_path: Optional[str] = None
    avatar_layout: str = "pip_bottom_right"


class ImageContract(BaseModel):
    """
    Complete visual package compiled for final rendering.
    """
    art_style_applied: str
    resolution: str
    scene_visuals: List[SceneVisualArtifact]
